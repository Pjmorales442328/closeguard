# data/bills_bank_gen.py — bills-sized October bank CSV that pays the demo bills, plus 3 honest traps (deterministic).
# Run from repo root:  python data/bills_bank_gen.py   -> data/synthetic/bank_bills_2026-10.csv (all 13 demo bills)
#                                                       + data/synthetic/bank_kit_2026-10.csv (only the judge kit's 9 bills)
import json
import sys
from datetime import date, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from data.world import VENDORS  # noqa: E402

SYN = Path(__file__).resolve().parent / "synthetic"
OUT, KIT_OUT = SYN / "bank_bills_2026-10.csv", SYN / "bank_kit_2026-10.csv"
KIT = ["B01", "B02", "B03", "B04", "B07", "B08", "B09", "B10", "B13"]  # judge kit bills (B11 is not in it: B03 is short-paid there)
REFUSED_AT_INTAKE = {"line_sum", "duplicate_invoice", "dates"}  # these bills never reach the ledger, so nobody pays them
SHORT_PAID = "B11.jpg"  # paid with two digits swapped: the amount does not match its bill (kit: B03.jpg)
DUPLICATE_OF = "B02.jpg"  # paid twice, same payee, amount and reference
HEADER = "# SYNTHETIC DATA — generated by data/bills_bank_gen.py from bills/manifest.json; no real company, vendor or bank\n"


def _canon(s: str) -> str:
    return next((v for v in VENDORS if v.casefold() == s.casefold()), s)


def _pay_day(t: dict) -> date:
    return min(date.fromisoformat(t["invoice_date"]) + timedelta(days=6), date(2026, 10, 30))


def _swap(amount: str) -> str:
    whole, cents = amount.split(".")
    return f"{whole[:-2]}{whole[-1]}{whole[-2]}.{cents}"  # 852.06 -> 825.06


def rows(only=None, short_paid=SHORT_PAID) -> list:
    bills = json.loads((SYN / "bills" / "manifest.json").read_text("utf-8"))["bills"]
    out = []
    for b in bills:
        if b["trap"] in REFUSED_AT_INTAKE or (only and b["file"][:3] not in only):
            continue
        t = b["truth"]
        amt = _swap(t["total"]) if b["file"] == short_paid else t["total"]
        out.append([_pay_day(t), amt, _canon(t["supplier"]), t["invoice_no"]])
        if b["file"] == DUPLICATE_OF:
            out.append([_pay_day(t) + timedelta(days=2), t["total"], _canon(t["supplier"]), t["invoice_no"]])
    out.append([date(2026, 10, 22), "640.00", "Quickfix Repairs", "QFX-10022"])  # a payee with no bill and not on the vendor list
    out.sort(key=lambda r: (r[0], r[3]))
    return [[f"BB{i:03d}", d.isoformat(), a, "DR", cp, ref, f"SYNTHETIC payment {cp}"] for i, (d, a, cp, ref) in enumerate(out, 1)]


def render(kit: bool = False) -> str:
    rs = rows(KIT, "B03.jpg") if kit else rows()
    lines = ["txn_id,date,amount,direction,counterparty,reference,memo"] + [",".join(r) for r in rs]
    return HEADER + "\n".join(lines) + "\n"


if __name__ == "__main__":
    for path, kit in ((OUT, False), (KIT_OUT, True)):
        path.write_text(render(kit), encoding="utf-8", newline="\n")
        print(f"wrote {path}")
