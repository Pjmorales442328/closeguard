# bench/report.py — renders bench/results/latest.json into summary.md. Every figure comes from the json, never typed.
RECOMMEND = [
    "Two tiers (core/rules_memo.py, core/rules_memo_flag.py): HARD refuses only markup, role prefixes, override phrases "
    "aimed at the checker and encoded/obfuscated text; SOFT flags finance words (approve, partial payment, discount, "
    "credit note, authorised...) and the approver must tick an acknowledgement (policy.memo_unacknowledged) to approve.",
    "This attack set was used to tune the rule, so its block rate is coverage of this list, not generalisation. The blind "
    "held-out sets in bench/heldout are the honest numbers; 'passed unflagged' is the figure that matters.",
    "Limit: paraphrases outside the phrase list pass or are only flagged. The numeric rules, SoD and human approval stop "
    "posting regardless of memo text; the memo rule is a tripwire plus a flag, not the control.",
]


def before_after(before: dict, after: dict) -> str:
    rows = [{"class": n, "before blocked": f"{before['classes'][n]['blocked']}/{v['trials']}", "after hard-blocked": f"{v['blocked']}/{v['trials']}",
             "after flagged": v.get("flagged", 0), "after unflagged": v["passed"]}
            for n, v in after["classes"].items() if n in before.get("classes", {})]
    rows.append({"class": "TOTAL", "before blocked": f"{before['blocked']}/{before['total']}", "after hard-blocked": f"{after['blocked']}/{after['total']}",
                 "after flagged": after.get("flagged", 0), "after unflagged": after["passed"]})
    return _t(rows, ["class", "before blocked", "after hard-blocked", "after flagged", "after unflagged"])


def _t(rows, cols):
    head = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    return head + "".join("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |\n" for r in rows)


def render(r: dict) -> str:
    m, a, c, t, k = r["metrics"], r["ablation"], r["cost"], r["timing"], r["attacks"]
    caught = sum(1 for f in r["faults"] if f["caught"])
    refused = sum(1 for f in r["faults"] if f["refused"])
    misses = [f for f in r["faults"] if not f["caught"]]
    out = [f"# Bench summary (generated by `python -m bench.run`; data synthetic, seed {r['seed']})\n",
           f"Run: {r['run_at']} · model {r['model']} ({r['model_mode']}) · gate {r['gate']}\n",
           "## Headline\n",
           f"- Faults refused: **{refused}/{m['faults']}**; refused with the expected rule: **{caught}/{m['faults']}**",
           f"- False refusals on legit lines: **{m['fp']}** of {m['lines'] - m['faults']} · precision {m['precision']} · recall {m['recall']}",
           f"- Gate OFF ablation: **{a['faulty_proposals_reaching_controller']}** faulty proposals would reach the controller "
           f"({a['proposals_reaching_controller']} proposals total); faults with no proposal at all: {len(a['faults_not_proposed'])}",
           f"- Model: {c['measured']['calls']} calls ({c['measured']['cached']} replayed from cache), "
           f"{c['measured']['total_tokens']} tokens, **${c['measured']['usd']:.4f}** at the published rate "
           f"(${c['measured']['usd_low']:.4f} at the third-party low rate)",
           f"- Projected full close ({c['projected_full_close']['calls']} calls): ${c['projected_full_close']['usd']:.4f} "
           f"(PROJECTION, see cost.price.note)",
           f"- Time: deterministic pipeline {t['deterministic_s']} s; full bench run {t['full_run_s']} s; "
           f"original model latency (sum, from cache) {c['measured']['model_seconds_original']} s",
           f"- Human baseline: {r['human_baseline']}",
           f"- Attack set (tuned-on, not generalisation): {k['blocked']}/{k['total']} hard-blocked, {k.get('flagged', 0)} flagged "
           f"for the approver, **{k['passed']} passed unflagged** (a pass is a finding, see below)\n",
           "## Per-fault table\n", _t(r["faults"], ["id", "type", "txn_id", "expected", "actual", "refused", "caught"]),
           "\n## Misses (expected rule not fired)\n"]
    out += [f"- {f['id']} {f['txn_id']}: expected {f['expected']}, got {f['actual']} ({'refused' if f['refused'] else 'ALLOWED'}): {f['detail']}"
            for f in misses] or ["- none"]
    out += ["\n## Price source\n", f"- {c['price']['usd_per_m_input']} $/M input, {c['price']['usd_per_m_output']} $/M output · "
            f"{c['price']['source']} (checked {c['price']['checked']})", f"- {c['price']['note']}",
            "\n## Attack classes (memo and reference trials per string)\n",
            _t([{"class": n, **v} for n, v in k["classes"].items()], ["class", "attacks", "trials", "blocked", "flagged", "passed"]),
            *(["\n### Before (bench/results/before.json, pre-hardening gate) vs after\n", before_after(r["attacks_before"], k)]
              if r.get("attacks_before") else []),
            "\n### Passes, unflagged (gate treated the text as data; nothing was posted)\n"]
    grouped = {}
    for p in k["passes"]:
        grouped.setdefault((p["class"], p["text"]), []).append(p["field"])
    out += [f"- [{c}] `{x!r}` ({'+'.join(f)})" for (c, x), f in grouped.items()] or ["- none"]
    out += ["\n### Flagged (allowed as data; the approver must acknowledge the flagged text)\n"]
    out += [f"- [{f['class']}] `{f['text']!r}` -> {f['flag']}" for f in k.get("flags", []) if f["field"] == "memo"] or ["- none"]
    d = k["downstream_controls"]
    out += [f"\nDownstream for every pass (measured on {d['txn_id']}): post without approval -> {d['post_without_approval']}; "
            f"self-approval -> {d['self_approval']}; wrong role -> {d['wrong_role']}. Memo text never changes amount, "
            "invoice or approval state, so a pass cannot post a number by itself.",
            "\n## Memo rule: what was applied and what remains a limit\n"] + [f"- {x}" for x in RECOMMEND]
    return "\n".join(out) + "\n"
